WITH muestra AS (
    SELECT
    FROM (values
        (1000::numeric),
        (0::numeric),
        (0::numeric,
        (NULL::numeric)
    ) AS v(valor)
)
SELECT
    AVG(valor) AS promedio_sin_coalesce
    COUNT(valor) AS denominador 3
FROM muestra;

